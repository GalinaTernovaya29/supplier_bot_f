# Вспомогательные функции
def load_db():
    with open(DB_FILE, "r", encoding="utf-8") as f:
        return json.load(f)

def save_db(db):
    with open(DB_FILE, "w", encoding="utf-8") as f:
        json.dump(db, f, ensure_ascii=False, indent=4)

def similar(a, b):
    return SequenceMatcher(None, a.lower(), b.lower()).ratio()

# Хранение временного фото перед названием
temp_photos = {}

@bot.message_handler(content_types=['photo', 'text'])
def handle_message(message):
    db = load_db()
    chat_id = message.chat.id

    # Фото
    if message.content_type == 'photo':
        file_id = message.photo[-1].file_id
        temp_photos[chat_id] = file_id
        bot.send_message(chat_id, random.choice([
            "Фото получено! Пожалуйста, пришлите название поставщика.",
            "Отлично, теперь пришлите название поставщика для этого фото."
        ]))
        return

    # Текст
    elif message.content_type == 'text':
        text = message.text.strip()
        if chat_id in temp_photos:
            file_id = temp_photos.pop(chat_id)
            # Сохраняем фото и название
            db[text] = file_id
            save_db(db)
            bot.send_message(chat_id, f"Сохранено: {text}")
        else:
            # Проверяем совпадения по тексту
            found = False
            for key in db.keys():
                if similar(key, text) > 0.8:
                    file_id = db[key]
                    bot.send_photo(chat_id, file_id, caption=key)
                    found = True
                    break
            if not found:
                bot.send_message(chat_id, "Фото для этого запроса не найдено. Пожалуйста, пришлите фото.")
        return


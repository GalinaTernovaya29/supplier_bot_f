# Временное хранение фото, ожидающих названия
pending_photos = {}

# Функция случайного приветствия
def random_greeting():
    return random.choice(greetings)

def random_joke():
    return random.choice(jokes)

def random_wise():
    return random.choice(wise_quotes)

# Основная логика обработки сообщений
@bot.message_handler(content_types=['text', 'photo'])
def handle_message(message):
    chat_id = message.chat.id
    user_id = message.from_user.id
    
    # Если пришло фото
    if message.content_type == 'photo':
        file_id = message.photo[-1].file_id
        pending_photos[user_id] = file_id
        bot.send_message(chat_id, "Фото получено. Пожалуйста, отправьте название поставщика для сохранения.")
        return

    # Если пришёл текст
    text = message.text.strip()
    
    if user_id in pending_photos:
        # Сохраняем фото с названием
        file_id = pending_photos.pop(user_id)
        database.append({"name": text, "file_id": file_id})
        with open(DB_FILE, "w", encoding="utf-8") as f:
            json.dump(database, f, ensure_ascii=False, indent=2)
        bot.send_message(chat_id, f"Сохранено! Название: {text}")
        return
    
    # Поиск по тексту
    matches = [item for item in database if text.lower() in item['name'].lower()]
    if matches:
        for item in matches:
            bot.send_photo(chat_id, item['file_id'], caption=item['name'])
    else:
        bot.send_message(chat_id, "Совпадений не найдено. Если хотите добавить, отправьте фото с названием.")

# Приветствие при старте
@bot.message_handler(commands=['start'])
def start(message):
    chat_id = message.chat.id
    bot.send_message(chat_id, f"{random_greeting()} {random_joke()} {random_wise()}")

# Запуск бота
